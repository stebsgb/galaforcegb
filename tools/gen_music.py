#!/usr/bin/env python3
"""Convert the original BBC Galaforce tunes (ref/src/MUSIC*.asm) and hand-made SFX into build/music.inc.

Tune streams: one byte per note = note(6 bits, 63 = rest) | duration index (2 bits); 0 ends the channel.
BBC pitch = note*4, f = 261.63 * 2^((p-53)/48).  Channels: 0 -> pulse 1, 1 -> pulse 2, 2 -> wave.
"""
import math, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from bbc import ROOT, REF

names = {"Rest": 63, "D1": 0, "D2": 64, "D3": 128, "D4": 192}

streams, order = {}, []
cur = None
for fn in ("MUSIC1.asm", "MUSIC2.asm", "MUSIC3.asm"):
    for line in open(os.path.join(REF, "src", fn), encoding="latin-1"):
        line = line.split("\\")[0].strip()
        if not line:
            continue
        m = re.match(r"\.(\w+)\s*(.*)", line)
        if m:
            cur = m.group(1)
            streams[cur] = []
            order.append(cur)
            line = m.group(2)
        if cur and line.startswith("EQUB"):
            for part in line.split(":"):
                part = part.strip()
                if part.startswith("EQUB"):
                    streams[cur].append(eval(re.sub(r'\b0+(\d)', r'\1', part[4:].strip()), {}, names) & 255)

blob, addr = bytearray(), {}
tables = {"SPT", "ENVTAB", "DURATAB"}
for lab in order:
    addr[lab] = len(blob)
    if lab not in tables:
        blob += bytes(streams[lab])

SPT, ENVTAB, DURATAB = streams["SPT"], streams["ENVTAB"], streams["DURATAB"]

# tune lookup table (.LT in MUSIC3.asm): addr1, label2, label3, speed idx, env idx, dur idx
text = open(os.path.join(REF, "src", "MUSIC3.asm"), encoding="latin-1").read()
rows = re.findall(r"EQUW (\w+):EQUB (\w+)-\w+:EQUB (\w+)-\w+:EQUB (\d+):EQUB (\d+):EQUB (\d+)", text)
LT = {"START": rows[0], "BETW": rows[1], "OVER": rows[2], "DEMO": rows[3], "LOST": rows[4], "ZONE": rows[5]}
MY_ORDER = ["START", "BETW", "LOST", "OVER", "ZONE", "DEMO"]   # MUS_* ids in main.asm

# BBC ENVELOPE number -> (GB start volume, decay pace)
# music sits below the effects so that the SFX punch through
ENV_NR12 = {2: (9, 2), 4: (8, 4), 5: (9, 3), 6: (9, 3), 7: (9, 2), 8: (9, 3)}

def nr12(e):
    v, p = ENV_NR12.get(e, (11, 3))
    return (v << 4) | p

def freq(note):
    return 261.63 * 2 ** ((note * 4 - 53) / 48)

def pulse_x(f):
    return max(0, min(2047, round(2048 - 131072 / f)))

def wave_x(f):
    return max(0, min(2047, round(2048 - 65536 / f)))

out = ["; generated by tools/gen_music.py", "MusicBlob:"]
for i in range(0, len(blob), 16):
    out.append("    db " + ",".join(str(b) for b in blob[i:i + 16]))

out.append("TuneTable:   ; 16 bytes each: 3 stream ptrs, 4 speeds, 3 NR12, wave gate, pad")
for name in MY_ORDER:
    a1, l2, l3, spt, env, dur = LT[name]
    spt, env, dur = int(spt), int(env), int(dur)
    spd = [SPT[spt - (3 - y)] for y in range(4)]
    e = [ENVTAB[env - (2 - c)] for c in range(3)]
    d = [DURATAB[dur - (2 - c)] for c in range(3)]
    gate = max(1, min(255, d[2] * 3))
    out.append(f"    ; {name}")
    out.append("    dw " + ",".join(f"MusicBlob+{addr[x]}" for x in (a1, l2, l3)))
    out.append("    db " + ",".join(str(x) for x in spd) + "," + ",".join(str(nr12(x)) for x in e) + f",{gate},0,0")

out.append("PulseFreq:")
out.append("    dw " + ",".join(str(pulse_x(freq(n))) for n in range(64)))
out.append("WaveFreq:")
out.append("    dw " + ",".join(str(wave_x(freq(n))) for n in range(64)))

samples = [round(7.5 + 7.5 * (2 / math.pi) * math.asin(math.sin(2 * math.pi * (i + 0.5) / 32))) for i in range(32)]
out.append("WaveTable:")
out.append("    db " + ",".join(str((samples[2 * i] << 4) | samples[2 * i + 1]) for i in range(16)))

# ---------------------------------------------------------------- SFX
# event: type (0 pulse1 NR10-14 | 1 pulse2 NR21-24 | 2 noise NR41-44), regs..., wait frames; 255 ends
def p1(sweep, duty, env, hz, w=0):
    x = pulse_x(hz)
    return [0, sweep, duty, env, x & 255, 0x80 | (x >> 8), w]

def p2(duty, env, hz, w=0):
    x = pulse_x(hz)
    return [1, duty, env, x & 255, 0x80 | (x >> 8), w]

def nz(env, nr43, w=0):
    return [2, 0, env, nr43, 0x80, w]

sfx = {}
sfx["FIRE"] = p1(0x1C, 0x80, 0xA1, 1400, 10)
sfx["BOOM"] = nz(0xF3, 0x64) + p1(0x2B, 0x80, 0xF3, 200, 24)
sfx["PDEATH"] = nz(0xF7, 0x75) + p1(0x3B, 0x80, 0xF6, 600, 90)
up = []
for hz, w in ((523, 5), (659, 5), (784, 5), (1047, 24)):
    up += p1(0, 0x80, 0xD3, hz, w)
sfx["ONEUP"] = up
sfx["HIT"] = nz(0xC1, 0x33) + p2(0x80, 0xC1, 900, 6)
last = []
for i in range(14):
    last += p2(0x40, 0xD2, 440 if i % 2 == 0 else 330, 6)
sfx["LAST"] = last

SFX_ORDER = ["FIRE", "BOOM", "PDEATH", "ONEUP", "HIT", "LAST"]    # SFX_* ids in main.asm
out.append("SfxTable:")
out.append("    dw " + ",".join("Sfx_" + n for n in SFX_ORDER))
for n in SFX_ORDER:
    out.append("Sfx_" + n + ":")
    out.append("    db " + ",".join(str(b) for b in sfx[n]) + ",255")

os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
open(os.path.join(ROOT, "build", "music.inc"), "w").write("\n".join(out) + "\n")
print("music blob", len(blob), "bytes")
